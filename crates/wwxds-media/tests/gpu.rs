//! GPU-to-CPU parity of the analysis planes on real media.
//!
//! When the machine provides Direct3D 11 and the benchmark clip is present,
//! this decodes the clip twice — once through the D3D11 backend and once
//! through the CPU filter — and compares every analysis plane byte for byte.
//! The two backends compute the same integer box filter
//! (`docs/Architecture.md` §4), so their planes must be identical; the
//! hardware decoder's luma is part of that claim and is what this test
//! actually pins down.
//!
//! The test needs no FFmpeg fixture script, only the 1080p benchmark clip and
//! a usable D3D11 device, and skips with a message when either is absent, so
//! CI machines without a GPU still pass.

use std::path::PathBuf;

use wwxds_media::decode::{FrameStream, GpuMode, ReaderOptions};

/// The 1080p benchmark clip. It lives in the gitignored target directory and
/// is generated by hand with the system FFmpeg; the test skips without it.
fn bench_clip() -> Option<PathBuf> {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../target/bench-1080p.mkv");
    path.is_file().then_some(path)
}

/// Digests every analysis plane of one run, FNV-1a 64 like the detector.
fn plane_digest(plane: &[u8]) -> u64 {
    let mut hash: u64 = 0xcbf29ce484222325;
    for byte in plane {
        hash ^= u64::from(*byte);
        hash = hash.wrapping_mul(0x100000001b3);
    }
    hash
}

/// Runs one backend over the whole clip and returns (backend, digests).
fn digest_run(path: &std::path::Path, gpu: GpuMode) -> (&'static str, Vec<u64>) {
    let mut stream = FrameStream::open(
        path,
        ReaderOptions {
            gpu,
            ..ReaderOptions::default()
        },
    )
    .unwrap_or_else(|error| panic!("the run could not be opened: {error}"));
    let backend = stream.gpu_backend();
    let mut digests = Vec::new();
    while let Some(frame) = stream
        .next_frame()
        .unwrap_or_else(|error| panic!("the run failed: {error}"))
    {
        digests.push(plane_digest(frame.luma()));
        stream.recycle(frame);
    }
    (backend, digests)
}

#[test]
fn gpu_analysis_planes_match_the_cpu_implementation_byte_for_byte() {
    let Some(path) = bench_clip() else {
        eprintln!("skipping: the 1080p benchmark clip is absent");
        return;
    };

    let (cpu_backend, cpu_digests) = digest_run(&path, GpuMode::Off);
    assert_eq!(cpu_backend, "cpu");
    let (gpu_backend, gpu_digests) = digest_run(&path, GpuMode::Auto);
    if gpu_backend != "d3d11" {
        // The machine has no usable D3D11 device for this clip; the CPU
        // fallback is the tested behavior everywhere else.
        eprintln!("skipping: the D3D11 backend is unavailable on this machine");
        return;
    }

    assert_eq!(
        cpu_digests.len(),
        gpu_digests.len(),
        "the backends decoded different frame counts"
    );
    assert!(
        !cpu_digests.is_empty(),
        "the benchmark clip produced no frames"
    );
    for (index, (cpu, gpu)) in cpu_digests.iter().zip(&gpu_digests).enumerate() {
        assert_eq!(
            cpu, gpu,
            "frame {index}: the GPU analysis plane differs from the CPU plane"
        );
    }
}
